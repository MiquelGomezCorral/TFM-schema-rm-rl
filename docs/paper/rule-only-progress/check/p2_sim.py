def same_behaviour(text_a, props_a, text_b, props_b, depth: int = 5) -> int:
    """Walk two machines side by side on every input sequence up to `depth`; return how many sequences matched.

    The inputs are x, y, both and neither, with x and y the first and last proposition of each machine. Raises
    on the first different reward or a different state count.
    """
    machines = [
        parse_paper_reward_machine(text, propositions=tuple(props))
        for text, props in ((text_a, props_a), (text_b, props_b))
    ]
    sizes = {
        len({t.source for t in m.transitions} | {t.destination for t in m.transitions})
        for m in machines
    }
    if len(sizes) != 1:
        raise ValueError(f"state counts differ: {sizes}")
    runtimes = [RewardMachineRuntime(m) for m in machines]
    inputs = [(False, False), (True, False), (False, True), (True, True)]
    matched = 0

    def explore(states, left: int) -> None:
        nonlocal matched
        if not left:
            return
        for x, y in inputs:
            steps = []
            for runtime, props, state in zip(runtimes, (props_a, props_b), states, strict=True):
                runtime.state = state
                steps.append(runtime.step({props[0]: x, props[-1]: y}))
            if abs(steps[0].reward - steps[1].reward) > TOLERANCE:
                raise ValueError(
                    f"rewards differ on input x={x} y={y}: {steps[0].reward} vs {steps[1].reward}"
                )
            matched += 1
            explore([step.destination for step in steps], left - 1)

    explore([m.initial_state for m in machines], depth)
    return matched


