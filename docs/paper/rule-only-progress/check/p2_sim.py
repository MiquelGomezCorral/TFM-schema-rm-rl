def run_trace(rm_text, captured, props, trace) -> dict:
    """Step rewards and total of `trace` on one machine; the episode stops on entering the well."""
    runtime = RewardMachineRuntime(parse_paper_reward_machine(rm_text, propositions=tuple(props)))
    state, rewards, ended = captured["initial"], [], "open"
    for token in trace.split():
        true_names = true_set(token, props)
        step = runtime.step({name: name in true_names for name in props})
        moved = product_step(captured, state, true_names)
        if moved is None or abs(step.reward - moved[1]) > TOLERANCE:
            raise ValueError(f"runtime and product disagree on {trace!r} at {token!r}")
        rewards.append(round(step.reward, 9) + 0.0)
        state = moved[0]
        if state == _WELL:
            ended = "well"
            break
    if state != _WELL:
        ended = captured["product"].labels[state][0].value
    return {"rewards": rewards, "total": round(sum(rewards), 9) + 0.0, "ended": ended}


