def stats(machine) -> dict:
    return {
        "states": len(machine.states),
        "rewards": sorted({round(t.reward, 3) for t in machine.transitions}),
    }


def reason(row) -> str:
    if row["has_final"]:
        return "has a final state: P2 does not apply"
    if not row["changed"]:
        return (
            "the clause is never left waiting: every state is already a target, nothing to measure"
        )
    return WHY[row["pattern"]]


def make_row(kind: tuple, recurrent: bool, today, p2, compiled: tuple) -> dict:
    """One machine: its text today and with P2, and the graphs and traces when P2 changes it.

    `kind` is (pattern, propositions, priority); `compiled` is (proposal, dfas).
    """
    pattern, props, priority = kind
    proposal, dfas = compiled
    has_final = today[0].reward_machine.final_state is not None
    suffix = "" if recurrent else " (recurrent off)"
    name = f"{pattern}({', '.join(props)}) {priority}{suffix}"
    row = {
        "name": name,
        "pattern": pattern,
        "propositions": props,
        "priority": priority,
        "recurrent": recurrent,
        "task": TASKS[pattern][0 if priority == "hard" else 1],
        "ltlf": proposal.clauses[0].ltlf_formula,
        "dfa": dfa_text(dfas[0]),
        "has_final": has_final,
        "well": bool(today[0].reward_machine.rejecting_states),
        "today": today[2],
        "p2": p2[2],
        "changed": today[2] != p2[2],
        "inert_soft": bool(today[0].inert_soft_clauses),
        "today_stats": stats(today[0].reward_machine),
        "p2_stats": stats(p2[0].reward_machine),
        "slug": f"{pattern}-{'-'.join(props)}.{priority}{'' if recurrent else '-off'}",
    }
    if has_final and row["changed"]:
        raise ValueError(f"{name}: has a final and P2 changed it")
    row["reason"] = reason(row)
    if row["changed"]:
        draw(today[0].reward_machine, GRAPHS / f"{row['slug']}.today.html")
        draw(p2[0].reward_machine, GRAPHS / f"{row['slug']}.p2.html")
        row["traces"] = [
            {
                "trace": trace,
                "case": case,
                "today": run_trace(today[2], today[1], props, trace),
                "p2": run_trace(p2[2], p2[1], props, trace),
            }
            for trace, case in TRACES[pattern]
        ]
    return row


def compile_rows() -> list[dict]:
    """Every machine of TEMPLATES, hard and soft, with the checks that need no rename."""
    GRAPHS.mkdir(parents=True, exist_ok=True)
    rows = []
    for pattern, props in TEMPLATES:
        for priority in ("hard", "soft"):
            proposal, dfas, modes = compile_pair(pattern, props, priority)
            if priority == "hard" and len(modes) > 1:
                raise ValueError(f"{pattern} hard differs with the recurrent switch")
            rows.extend(
                make_row((pattern, props, priority), recurrent, today, p2, (proposal, dfas))
                for recurrent, today, p2 in modes
            )
    # the check: hard Existence / ExistenceTwo unchanged (a machine with a final: see make_row)
    assert all(
        not row["changed"]
        for row in rows
        if row["pattern"] in ("Existence", "ExistenceTwo") and row["priority"] == "hard"
    )
    return rows


def rename_checks() -> list[dict]:
    """A rename changes nothing: each renamed example behaves like the one it replaces."""
    renames = []
    for pattern, old_names in {**ORIGINALS, "Response (earlier user task)": USER_TASK}.items():
        pattern = pattern.split(" ")[0]
        new_names = dict(TEMPLATES)[pattern]
        for priority in ("hard", "soft"):
            _, _, old_modes = compile_pair(pattern, old_names, priority)
            _, _, new_modes = compile_pair(pattern, new_names, priority)
            assert [m[0] for m in old_modes] == [m[0] for m in new_modes], (
                f"{pattern} {priority}: recurrent modes differ"
            )
            for (recurrent, old_today, old_p2), (_, new_today, new_p2) in zip(
                old_modes, new_modes, strict=True
            ):
                matched = same_behaviour(old_today[2], old_names, new_today[2], new_names)
                assert matched == same_behaviour(old_p2[2], old_names, new_p2[2], new_names)
                renames.append(
                    {
                        "pattern": pattern,
                        "from": old_names,
                        "to": new_names,
                        "priority": priority,
                        "recurrent": recurrent,
                        "sequences_matched": matched,
                    }
                )
    return renames


def write_outputs(rows: list[dict], renames: list[dict]) -> list[str]:
    """Write results.json, rm-texts.txt and traces.txt, each ending with one newline."""
    (HERE / "results.json").write_text(
        json.dumps({"rows": rows, "rename_check": renames}, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    texts, traces = [], []
    for row in rows:
        texts.append(
            f"===== {row['name']} · changed: {row['changed']} · {row['reason']}\n--- today\n{row['today']}\n--- P2\n{row['p2']}\n"
        )
        for t in row.get("traces", []):
            traces.append(
                f"{row['name']} | {t['trace']!r} ({t['case']}): today {t['today']['rewards']} = {t['today']['total']:g} [{t['today']['ended']}]"
                f" | P2 {t['p2']['rewards']} = {t['p2']['total']:g} [{t['p2']['ended']}]"
            )
    # blocks are separated by a blank line; the last one ends with its RM text's single newline
    (HERE / "rm-texts.txt").write_text("\n".join(texts).rstrip("\n") + "\n", encoding="utf-8")
    (HERE / "traces.txt").write_text("\n".join(traces) + "\n", encoding="utf-8")
    return traces


def main() -> None:
    rows = compile_rows()
    renames = rename_checks()
    traces = write_outputs(rows, renames)
    for row in rows:
        print(
            f"{row['name']:60} final {row['has_final']!s:5} well {row['well']!s:5} changed {row['changed']!s:5} {row['reason']}"
        )
    print()
    print("\n".join(traces))
    print()
    for check in renames:
        print(
            f"rename {check['pattern']} {check['priority']}{'' if check['recurrent'] else ' (recurrent off)'}: "
            f"{check['from']} -> {check['to']}: same rewards, today and with P2, on {check['sequences_matched']:,} input sequences"
        )
    print(
        f"\n{len(rows)} machines, {sum(r['changed'] for r in rows)} changed; positive-cycle check false on every machine; "
        f"every machine with a final unchanged; every renamed example matches the one it replaces"
    )


if __name__ == "__main__":
    main()
