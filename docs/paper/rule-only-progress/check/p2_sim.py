"""Proposal P2, simulated on the clauses alone: progress toward the states where every clause is fine.

Run from the repository root, inside RM_RL_env (no LLM calls; MONA and FL-AT run locally):

    PYTHONPATH=app python -W ignore docs/paper/rule-only-progress/check/p2_sim.py

P2, only for a task with no final (no hard goal), as a runtime patch of `reward_layer._price_edges`:
targets = product states where no clause is PENDING; their outgoing edges and the edges into the well are
cut for measuring; `remaining(u)` = longest steps to a target on the cut graph, cycles collapsed, 0 where no
target is reachable; every real edge (well edges excluded) pays 0.1 * (remaining(source) - remaining(destination))
on top of today's price. No tracked file is edited.

Compiles each of the eight IBM templates alone, hard and soft (soft with the recurrent soft rules on, and off
where that changes the machine), once as today and once with P2. Writes results.json, rm-texts.txt and
traces.txt next to this file, and the graphs of the changed machines to ../graphs/. Fails if a P2 machine has
a positive reward cycle, if a machine with a final changes, or if a renamed example is not the same machine as
the example it replaces.
"""

