def selection(pattern: str, propositions: list[str], priority: str) -> ProposalSelection:
    template_class, _ = SUPPORTED_TEMPLATES[pattern]
    return ProposalSelection(
        normalized_clause=f"{pattern}({', '.join(propositions)})",
        pattern=pattern,
        propositions=tuple(propositions),
        priority=PriorityLevel(priority),
        template=template_class(*(Atomic(name) for name in propositions)),
    )


def draw(machine, path: Path) -> None:
    path.write_text(render_elements_html(reward_machine_to_elements(machine)), encoding="utf-8")


def build_captured(dfas, soft, recurrent: bool):
    """Run `build_reward_machine` once and keep the product and the priced edges it used.

    The numeric RM renumbers states, so the clause labels of a step are only recoverable from the
    layer's own product: wrap its two private stages and read what they receive.
    """
    captured = {}
    clause_product, structure = reward_layer._clause_product, reward_layer._structure

    def wrapped_product(*args, **kwargs):
        captured["product"] = clause_product(*args, **kwargs)
        return captured["product"]

    def wrapped_structure(*args, **kwargs):
        captured["initial"], captured["priced"] = args[0], args[1]
        return structure(*args, **kwargs)

    reward_layer._clause_product, reward_layer._structure = wrapped_product, wrapped_structure
    try:
        result = build_reward_machine(
            copy.deepcopy(list(dfas)), soft, recurrent_soft_penalty=recurrent
        )
    finally:
        reward_layer._clause_product, reward_layer._structure = clause_product, structure
    return result, captured


def true_set(token: str, propositions: list[str]) -> set[str]:
    names = {"x": propositions[0], "y": propositions[-1]}
    return {names[part] for part in token.split("+") if part in names}


def product_step(captured, state, true_names):
    """Move the layer's product one step; None when no priced edge leaves `state`."""
    product = captured["product"]
    alphabet = sorted(product.alphabet)
    valuation = {name: name in true_names for name in alphabet}
    for edge, reward in captured["priced"]:
        if edge.source == state and evaluate_boolean_guard(
            parse_boolean_guard(edge.guard, alphabet), valuation
        ):
            return edge.destination, reward
    return None


# ======================================================================================
#                                      THE PATCH
# ======================================================================================


def remaining_steps(edges, targets, nodes) -> dict[str, int]:
    """Longest steps from each node to a target, cycles collapsed (the body of `_progress`); 0 if none is reachable."""
    dag = nx.condensation(reward_layer._graph(nodes, edges))
    steps, reaches = {}, {}
    for component in reversed(list(nx.topological_sort(dag))):
        if not targets.isdisjoint(dag.nodes[component]["members"]):
            steps[component], reaches[component] = 0, True
            continue
        ahead = [steps[child] for child in dag.successors(component) if reaches[child]]
        reaches[component] = bool(ahead)
        steps[component] = 1 + max(ahead) if ahead else 0
    return {state: steps[component] for state, component in dag.graph["mapping"].items()}


def p2_price_edges(edges, product, finals, soft_clauses):
    """Today's prices, plus P2's progress toward the fine states when the task has no final."""
    priced, paying = _TODAY_PRICE(edges, product, finals, soft_clauses)
    if finals:
        return priced, paying
    real = [edge for edge in edges if edge.destination != _WELL]
    nodes = {edge.source for edge in edges} | {edge.destination for edge in real}
    targets = {state for state in nodes if ClauseState.PENDING not in product.labels[state]}
    remaining = remaining_steps(
        [edge for edge in real if edge.source not in targets], targets, nodes
    )
    return [
        (
            edge,
            reward
            if edge.destination == _WELL
            else round(
                reward
                + Configuration.PROGRESS_REWARD
                * (remaining[edge.source] - remaining[edge.destination]),
                9,
            ),
        )
        for edge, reward in priced
    ], paying


@contextmanager
def p2_patch():
    reward_layer._price_edges = p2_price_edges
    try:
        yield
    finally:
        reward_layer._price_edges = _TODAY_PRICE


def build(dfas, soft, recurrent: bool, p2: bool):
    with p2_patch() if p2 else nullcontext():
        result, captured = build_captured(dfas, soft, recurrent)
    return result, captured, serialize_reward_machine(result.reward_machine)


def compile_pair(pattern: str, props: list[str], priority: str):
    """The clause alone, compiled today and with P2, for each recurrent-soft setting that matters."""
    proposal = materialize_proposal(f"{pattern} {priority}", [selection(pattern, props, priority)])
    dfas = compile_dfas(proposal, CONFIG)
    soft = [clause.priority is PriorityLevel.SOFT for clause in proposal.clauses]
    today_off, today_on = build(dfas, soft, False, False), build(dfas, soft, True, False)
    modes = (
        [(True, today_on)]
        if today_off[2] == today_on[2]
        else [(False, today_off), (True, today_on)]
    )
    return (
        proposal,
        dfas,
        [(recurrent, today, build(dfas, soft, recurrent, True)) for recurrent, today in modes],
    )


